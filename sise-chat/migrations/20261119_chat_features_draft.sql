-- SISE public chat: optional feature tables
-- FREE / SAFE DRAFT
-- This file is intentionally NOT applied to Supabase production.
-- Tables are created with RLS enabled and NO client policies, so browser clients
-- cannot read or write them until validated RPCs/policies are added.
-- Realtime typing/online indicators should use Supabase Realtime Presence/Broadcast;
-- do not persist keystrokes or create a paid Supabase branch for this.

begin;

create table if not exists public.chat_reactions (
  id bigint generated by default as identity primary key,
  message_id bigint not null references public.chat_messages(id) on delete cascade,
  uid text not null,
  emoji text not null check (emoji in ('❤️','😂','😍','👍','🔥','👏','😢','🎉')),
  created_at timestamptz not null default now(),
  constraint chat_reactions_message_uid_emoji_key unique (message_id, uid, emoji)
);

create index if not exists chat_reactions_message_id_idx
  on public.chat_reactions(message_id);

create table if not exists public.chat_reads (
  message_id bigint not null references public.chat_messages(id) on delete cascade,
  uid text not null,
  read_at timestamptz not null default now(),
  primary key (message_id, uid)
);

create index if not exists chat_reads_uid_read_at_idx
  on public.chat_reads(uid, read_at desc);

alter table public.chat_reactions enable row level security;
alter table public.chat_reads enable row level security;

comment on table public.chat_reactions is
  'SISE chat reactions. RLS intentionally has no client policies until token-validated RPCs are installed.';
comment on table public.chat_reads is
  'SISE chat read receipts. RLS intentionally has no client policies until token-validated RPCs are installed.';

commit;
